import {compile} from 'tailwindcss';
import {readFile,writeFile,readdir} from 'node:fs/promises';
const root=new URL('../src/lib/modules/routingtales/',import.meta.url),sources=[];
async function visit(url){for(const f of await readdir(url,{withFileTypes:true})){const path=new URL(f.name+(f.isDirectory()?'/':''),url);if(f.isDirectory())await visit(path);else if(f.name.endsWith('.svelte'))sources.push(await readFile(path,'utf8'));}}
await visit(root);
const theme=await readFile(new URL('../node_modules/tailwindcss/theme.css',import.meta.url),'utf8');
const compiler=await compile(theme+'\n@theme { --color-primary: #517146; --color-primary-dark: #35502f; }\n@tailwind utilities;');
const candidates=[...new Set(sources.join('\n').match(/[A-Za-z0-9_!:/.[\]#%()&=,+-]+/g))];
const css=compiler.build(candidates).replace(':root, :host','&');
await writeFile(new URL('utilities.css',root),'/* Generated by npm run modules:styles. Utility rules are confined to copied players. */\n.routing-module {\n'+css+'\n}\n');
console.log('RoutingTales utilities generated:',css.length,'bytes');
